#!/usr/bin/env node
// Single version source: the root VERSION file. Writes it into
//   - engine / sidecar / clients/desktop package.json "version" (and their package-lock.json workspace entries)
//   - engine/src/version.ts (ENGINE_VERSION, reported in the protocol `ready` event)
//   - project.yml MARKETING_VERSION (CFBundleShortVersionString) and CURRENT_PROJECT_VERSION
//     (CFBundleVersion = `git rev-list --count HEAD` at the time of the sync)
//
//   node scripts/sync-version.mjs          write (make version)
//   node scripts/sync-version.mjs --check  exit 1 listing what is out of sync (make test); the build
//                                          number is not checked — it moves with every commit.
//
// Edits are textual (formatting and key order kept). package-lock.json keeps its mtime: a version-only
// edit there does not make scripts/build-sidecar.sh reinstall node_modules.
import { execFileSync } from "node:child_process";
import { readFileSync, statSync, utimesSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");
const version = readFileSync(join(root, "VERSION"), "utf8").trim();
if (!/^\d+\.\d+\.\d+(-[0-9A-Za-z.-]+)?$/.test(version)) {
  console.error(`VERSION: "${version}" is not a semver x.y.z[-pre]`);
  process.exit(1);
}

function buildNumber() {
  try {
    return execFileSync("git", ["rev-list", "--count", "HEAD"], { cwd: root, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).trim();
  } catch {
    return null;
  }
}

/** [file, transform(text) → text, checked?, keepMtime?] */
const packages = ["engine", "sidecar", "clients/desktop"];
const edits = [
  ...packages.map((dir) => [
    `${dir}/package.json`,
    (t) => t.replace(/^(\s*"version"\s*:\s*")[^"]*(")/m, `$1${version}$2`),
  ]),
  [
    "package-lock.json",
    (t) => {
      for (const dir of packages) {
        const re = new RegExp(`(\\n    "${dir.replace(/[/.]/g, "\\$&")}": \\{\\n      "name": "[^"]+",\\n      "version": ")[^"]*(")`);
        t = t.replace(re, `$1${version}$2`);
      }
      return t;
    },
    true,
    true,
  ],
  [
    "engine/src/version.ts",
    () => `// Generated by scripts/sync-version.mjs from the root VERSION file — do not edit.\nexport const ENGINE_VERSION = "${version}";\n`,
  ],
  [
    "project.yml",
    (t, forCheck) => {
      t = t.replace(/^(\s*MARKETING_VERSION:\s*)"[^"]*"/m, `$1"${version}"`);
      const build = forCheck ? null : buildNumber();
      if (build) t = t.replace(/^(\s*CURRENT_PROJECT_VERSION:\s*)"[^"]*"/m, `$1"${build}"`);
      return t;
    },
  ],
];

const stale = [];
for (const [rel, transform, , keepMtime] of edits) {
  const file = join(root, rel);
  let before = "";
  try {
    before = readFileSync(file, "utf8");
  } catch {
    // generated file not there yet
  }
  if (check) {
    // the build number is excluded from the check: compare with CURRENT_PROJECT_VERSION left as is
    if (transform(before, true) !== before) stale.push(rel);
    continue;
  }
  const after = transform(before, false);
  if (after === before) continue;
  const st = keepMtime ? statSync(file) : null;
  writeFileSync(file, after);
  if (st) utimesSync(file, st.atime, st.mtime);
  console.log(`version ${version} → ${rel}`);
}

if (check) {
  if (stale.length > 0) {
    console.error(`version out of sync with VERSION (${version}): ${stale.join(", ")}\nrun: make version`);
    process.exit(1);
  }
  console.log(`version ${version}: in sync`);
}
