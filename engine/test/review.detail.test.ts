import { afterEach, describe, expect, it } from "vitest";
import { chmodSync, renameSync } from "node:fs";
import { join } from "node:path";
import { GitCheckpoint } from "../src/git/checkpoint.js";
import { annotateDetail, classifyGenerated, generatedByContent, generatedByPath, whitespaceOnlyPaths, type DetailedFile } from "../src/review/detail.js";
import { makeTempDir, removeDir, sh, write } from "./helpers/repo.js";

const dirs: string[] = [];
afterEach(() => {
  for (const d of dirs.splice(0)) removeDir(d);
});

function repo(): string {
  const dir = makeTempDir("rg-detail");
  dirs.push(dir);
  sh(dir, "init", "-q");
  sh(dir, "config", "user.email", "t@example.com");
  sh(dir, "config", "user.name", "T");
  sh(dir, "config", "core.autocrlf", "false");
  return dir;
}

describe("generated by path / content (§34.7)", () => {
  it.each([
    ["package-lock.json", "lockfile"],
    ["web/yarn.lock", "lockfile"],
    ["pnpm-lock.yaml", "lockfile"],
    ["Cargo.lock", "lockfile"],
    ["go.sum", "lockfile"],
    ["ios/App.xcworkspace/xcshareddata/swiftpm/Package.resolved", "lockfile"],
    ["gradle.lockfile", "lockfile"],
    ["static/app.min.js", "minified"],
    ["static/site.min.css", "minified"],
    ["static/app.js.map", "minified"],
  ])("%s → %s", (path, kind) => {
    expect(generatedByPath(path)).toBe(kind);
  });

  it("ordinary paths are not generated by name", () => {
    for (const p of ["src/Main.java", "package.json", "lock.ts", "docs/mapping.md", "min.js"]) expect(generatedByPath(p)).toBeNull();
  });

  it("markers within the first 5 lines (≤ 1 KB); a long line among the first 5 of a .js / .css file", () => {
    expect(generatedByContent("api/Gen.java", Buffer.from("// Code generated by protoc. DO NOT EDIT.\npackage x;\n"))).toBe("generated");
    expect(generatedByContent("api/schema.ts", Buffer.from("/**\n * @generated by graphql-codegen\n */\n"))).toBe("generated");
    expect(generatedByContent("api/Late.java", Buffer.from("a\nb\nc\nd\ne\n// DO NOT EDIT\n"))).toBeNull();
    expect(generatedByContent("api/Far.java", Buffer.from("x".repeat(1100) + "\n@generated\n"))).toBeNull();
    expect(generatedByContent("web/vendor.js", Buffer.from("!function(){" + "a,".repeat(800) + "}();\n"))).toBe("minified");
    expect(generatedByContent("web/app.ts", Buffer.from("const x = '" + "a".repeat(1200) + "';\n"))).toBeNull();
    expect(generatedByContent("src/Main.java", Buffer.from("class Main {}\n"))).toBeNull();
  });
});

describe("classifyGenerated / whitespaceOnlyPaths / annotateDetail (§34.7)", () => {
  it("gitattributes linguist-generated / -diff, markers, lockfiles; whitespace-only modifications and renames", async () => {
    const dir = repo();
    write(dir, ".gitattributes", "gen/** linguist-generated\n*.snap -diff\nkeep/** linguist-generated=false\n*.png binary\n");
    write(dir, "src/A.java", "class A {\n  int a = 1;\n}\n");
    write(dir, "src/B.java", "class B {\n  int b = 1;\n}\n");
    write(dir, "src/Old.java", "class Old {\n  int a;\n  int b;\n  int c;\n}\n");
    write(dir, "mode.sh", "echo hi\n");
    write(dir, "package-lock.json", '{"v":1}\n');
    sh(dir, "add", "-A");
    sh(dir, "commit", "-qm", "init");
    const cp = new GitCheckpoint(dir);
    const a = await cp.snapshot();
    write(dir, "src/A.java", "class A {\n    int a = 1;   \n}\n"); // whitespace only
    write(dir, "src/B.java", "class B {\n  int b = 2;\n}\n"); // a real change
    renameSync(join(dir, "src/Old.java"), join(dir, "src/New.java"));
    write(dir, "src/New.java", "class Old {\n  int a;\n   int b;\n  int c;\n}\n"); // renamed + whitespace
    chmodSync(join(dir, "mode.sh"), 0o755); // mode only: not "whitespace only"
    // Windows: git does not read the executable bit from disk (core.fileMode false) — the index carries it to the snapshot.
    if (process.platform === "win32") sh(dir, "update-index", "--chmod=+x", "mode.sh");
    write(dir, "package-lock.json", '{"v":2}\n');
    write(dir, "gen/api.ts", "export const x = 1;\n");
    write(dir, "keep/real.ts", "// DO NOT EDIT\nexport const y = 1;\n");
    write(dir, "ui/out.snap", "snapshot\n");
    write(dir, "src/Proto.java", "// Code generated by protoc-gen-java. DO NOT EDIT.\nclass Proto {}\n");
    write(dir, "img/logo.png", Buffer.from([0x89, 0x50, 0x4e, 0x47, 0, 1, 2, 3]));
    const b = await cp.snapshot();
    const files: DetailedFile[] = await cp.changes(a, b);
    expect(files.map((f) => [f.path, f.status])).toEqual([
      ["gen/api.ts", "A"],
      ["img/logo.png", "A"],
      ["keep/real.ts", "A"],
      ["mode.sh", "M"],
      ["package-lock.json", "M"],
      ["src/A.java", "M"],
      ["src/B.java", "M"],
      ["src/New.java", "R"],
      ["src/Proto.java", "A"],
      ["ui/out.snap", "A"],
    ]);
    const kinds = await classifyGenerated(cp, files);
    // linguist-generated=false is the user's override (as on GitHub): a marker in the file does not fold it.
    expect(Object.fromEntries(kinds)).toEqual({
      "gen/api.ts": "generated",
      "package-lock.json": "lockfile",
      "src/Proto.java": "generated",
      "ui/out.snap": "generated",
    });
    expect([...(await whitespaceOnlyPaths(cp, a, b, files))].sort()).toEqual(["src/A.java", "src/New.java"]);
    await annotateDetail(cp, files, a, b);
    const by = Object.fromEntries(files.map((f) => [f.path, [f.generated ?? null, f.whitespaceOnly ?? null]]));
    expect(by["src/A.java"]).toEqual([null, true]);
    expect(by["src/B.java"]).toEqual([null, null]);
    expect(by["mode.sh"]).toEqual([null, null]);
    expect(by["package-lock.json"]).toEqual(["lockfile", null]);
    // Re-annotating a rebuilt list drops what no longer holds.
    const again = files.map((f) => ({ ...f, generated: "minified" as const, whitespaceOnly: true as const }));
    await annotateDetail(cp, again, a, b);
    expect(again.find((f) => f.path === "src/B.java")).not.toHaveProperty("whitespaceOnly");
    expect(again.find((f) => f.path === "src/B.java")).not.toHaveProperty("generated");
  });

  it("never fails: a broken tree or a missing repository leaves the files unannotated", async () => {
    const dir = repo();
    const cp = new GitCheckpoint(dir);
    const files = [{ path: "x.ts", oldPath: null, status: "M" as const, added: 1, deleted: 1, isBinary: false, tools: [], toolUseIds: [], state: "pending" as const }];
    await annotateDetail(cp, files, "0".repeat(40), "1".repeat(40));
    expect(files[0]).not.toHaveProperty("whitespaceOnly");
  });
});
